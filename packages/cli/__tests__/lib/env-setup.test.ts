import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import * as path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { runEnvSetup } from "../../src/lib/env-setup.js";
import { parseAssignedEnvKeys } from "../../src/lib/machine-secrets.js";
import { type CLIStore, createStore } from "../../src/ui/store.js";

/** Headless store: answers every pipeline prompt so runEnvSetup never blocks. */
function makeHeadlessStore(
  onAsk?: (id: string, meta: unknown) => void,
): CLIStore {
  const store = createStore();
  store.pushAnswerResolver((id, meta) => {
    onAsk?.(id, meta);
    switch (id) {
      case "env_method":
        return "manual";
      case "env_alternatives":
        return { selectedGroups: [], values: {} };
      case "env_group":
        return {};
      case "env_var":
      case "setup_mode":
        return "";
      default:
        return undefined;
    }
  });
  return store;
}

/** Every group and variable name runEnvSetup asked about, in a temp repo. */
async function askedNames(
  repo: string,
  mode: "selfhost" | "developer",
): Promise<string[]> {
  const asked: string[] = [];
  const store = makeHeadlessStore((id, meta) => {
    const { groupName, varName } = (meta ?? {}) as {
      groupName?: string;
      varName?: string;
    };
    if (id === "env_group" && groupName) asked.push(groupName);
    if (id === "env_var" && varName) asked.push(varName);
  });
  await runEnvSetup(store, repo, mode);
  return asked;
}

describe("runEnvSetup env policy", () => {
  const dirs: string[] = [];

  afterEach(() => {
    for (const dir of dirs.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  function makeRepo(): string {
    const dir = mkdtempSync(path.join(tmpdir(), "gaia-env-setup-"));
    // Mirror a real clone's layout: the writers expect these directories to
    // exist (a fresh clone always has them).
    mkdirSync(path.join(dir, "apps", "api"), { recursive: true });
    mkdirSync(path.join(dir, "apps", "web"), { recursive: true });
    mkdirSync(path.join(dir, "infra", "docker"), { recursive: true });
    dirs.push(dir);
    return dir;
  }

  function readApiEnv(repo: string): string {
    return readFileSync(path.join(repo, "apps", "api", ".env"), "utf-8");
  }

  it("selfhost mode writes ENV=selfhost + AUTH_MODE=local + machine secrets", async () => {
    const repo = makeRepo();
    const store = makeHeadlessStore();

    await runEnvSetup(store, repo, "selfhost");

    const content = readApiEnv(repo);
    const keys = parseAssignedEnvKeys(content);

    expect(content).toMatch(/^ENV=selfhost$/m);
    expect(content).toMatch(/^AUTH_MODE=local$/m);

    // Every machine secret generated and hex-formatted.
    for (const name of [
      "AGENT_SECRET",
      "BOT_SESSION_TOKEN_SECRET",
      "EMAIL_UNSUBSCRIBE_SECRET",
      "SHARE_GRANT_SECRET",
      "GAIA_BOT_API_KEY",
    ]) {
      expect(keys.has(name)).toBe(true);
      expect(content).toMatch(new RegExp(`^${name}=[0-9a-f]{64}$`, "m"));
    }

    // Infra defaults applied for selfhost.
    expect(content).toMatch(/^MONGO_DB=mongodb:\/\/mongo:27017\/gaia$/m);
  });

  it("never asks a self-host install about hosted-only groups", async () => {
    const hostedOnly = [
      "WorkOS Authentication",
      "Cloudinary Media Storage",
      "Browser Host",
      "Dodo Payments",
      "BLOG_BEARER_TOKEN",
      "SENTRY_DSN",
      "Posthog Analytics",
    ];

    const selfhost = await askedNames(makeRepo(), "selfhost");
    const developer = await askedNames(makeRepo(), "developer");

    expect(selfhost.filter((name) => hostedOnly.includes(name))).toEqual([]);
    // Generated by the CLI, configured in the web wizard, or unused off GAIA Cloud.
    const notPrompted = [
      "SHARE_GRANT_SECRET",
      "E2B_API_KEY",
      "LLAMA_INDEX_KEY",
      "OPENWEATHER_API_KEY",
    ];
    expect(selfhost.filter((name) => notPrompted.includes(name))).toEqual([]);
    expect(selfhost).toContain("TAVILY_API_KEY");
    expect(developer).toEqual(expect.arrayContaining(hostedOnly));
  });

  it("never asks for an AI provider that --llm-provider already chose", async () => {
    const repo = makeRepo();
    const asked: string[] = [];
    const statuses: string[] = [];
    const store = makeHeadlessStore((id) => asked.push(id));
    store.on("change", (state: { status: string }) =>
      statuses.push(state.status),
    );

    await runEnvSetup(store, repo, "selfhost", undefined, {
      llmProvider: "openai",
    });

    expect(asked).not.toContain("env_alternatives");
    expect(statuses).not.toContain("Choose an AI provider…");
    expect(readApiEnv(repo)).not.toMatch(/^OPENAI_API_KEY=/m);
  });

  it("developer mode keeps ENV=development without AUTH_MODE", async () => {
    const repo = makeRepo();
    const store = makeHeadlessStore();

    await runEnvSetup(store, repo, "developer");

    const content = readApiEnv(repo);
    expect(content).toMatch(/^ENV=development$/m);
    expect(content).not.toMatch(/^AUTH_MODE=/m);
    // Developer infra defaults.
    expect(content).toMatch(/^MONGO_DB=mongodb:\/\/localhost:27017\/gaia$/m);
  });

  it("merge-don't-clobber: pre-existing secrets survive a rerun", async () => {
    const repo = makeRepo();
    const firstRunEnv = path.join(repo, "apps", "api", ".env");
    const preExisting = [
      "# GAIA Environment Configuration",
      "AGENT_SECRET=keep-me-untouched",
      "",
    ].join("\n");

    // Simulate an existing install: write the secret before setup runs.
    writeFileSync(firstRunEnv, preExisting);

    const store = makeHeadlessStore();
    await runEnvSetup(store, repo, "selfhost");

    const content = readApiEnv(repo);
    expect(content).toMatch(/^AGENT_SECRET=keep-me-untouched$/m);
    // The other two are freshly generated.
    expect(content).toMatch(/^BOT_SESSION_TOKEN_SECRET=[0-9a-f]{64}$/m);
    expect(content).toMatch(/^EMAIL_UNSUBSCRIBE_SECRET=[0-9a-f]{64}$/m);

    // A .bak backup of the previous file exists (writer behavior).
    const backup = readFileSync(`${firstRunEnv}.bak`, "utf-8");
    expect(backup).toContain("keep-me-untouched");
  });

  it("secrets are stable across two consecutive selfhost runs on the same repo", async () => {
    const repo = makeRepo();
    const extract = (content: string, name: string): string | undefined =>
      content.match(new RegExp(`^${name}=([0-9a-f]{64})$`, "m"))?.[1];

    await runEnvSetup(makeHeadlessStore(), repo, "selfhost");
    const firstContent = readApiEnv(repo);

    await runEnvSetup(makeHeadlessStore(), repo, "selfhost");
    const secondContent = readApiEnv(repo);

    for (const name of [
      "AGENT_SECRET",
      "BOT_SESSION_TOKEN_SECRET",
      "EMAIL_UNSUBSCRIBE_SECRET",
      "INSTANCE_SECRET",
    ]) {
      const generated = extract(firstContent, name);
      expect(generated).toBeDefined();
      expect(extract(secondContent, name)).toBe(generated);
    }
  });

  it("a rerun keeps every value the user edited in apps/api/.env", async () => {
    const repo = makeRepo();
    await runEnvSetup(makeHeadlessStore(), repo, "selfhost", undefined, {
      domain: "gaia.example.com",
    });
    const envPath = path.join(repo, "apps", "api", ".env");
    writeFileSync(
      envPath,
      readApiEnv(repo)
        .replace(/^MONGO_DB=.*$/m, "MONGO_DB=mongodb://my-mongo:27017/mine")
        .replace(/^AUTH_MODE=.*$/m, "AUTH_MODE=workos"),
    );

    await runEnvSetup(makeHeadlessStore(), repo, "selfhost");

    const content = readApiEnv(repo);
    expect(content).toMatch(/^MONGO_DB=mongodb:\/\/my-mongo:27017\/mine$/m);
    expect(content).toMatch(/^AUTH_MODE=workos$/m);
    expect(content).toMatch(/^HOST=https:\/\/gaia\.example\.com$/m);
    expect(content).toMatch(/^SETUP_MODE=selfhost$/m);
  });

  it("a rerun's explicit flag still replaces the stored value", async () => {
    const repo = makeRepo();
    await runEnvSetup(makeHeadlessStore(), repo, "selfhost", undefined, {
      domain: "old.example.com",
    });

    await runEnvSetup(makeHeadlessStore(), repo, "selfhost", undefined, {
      domain: "new.example.com",
    });

    expect(readApiEnv(repo)).toMatch(/^HOST=https:\/\/new\.example\.com$/m);
  });

  it("switching mode takes the new mode's infra addresses", async () => {
    const repo = makeRepo();
    await runEnvSetup(makeHeadlessStore(), repo, "developer");

    await runEnvSetup(makeHeadlessStore(), repo, "selfhost");

    const content = readApiEnv(repo);
    expect(content).toMatch(/^MONGO_DB=mongodb:\/\/mongo:27017\/gaia$/m);
    expect(content).toMatch(/^ENV=selfhost$/m);
    expect(content).toMatch(/^SETUP_MODE=selfhost$/m);
  });

  it("serves selfhost from one origin: proxy profile on, API on the web port", async () => {
    const repo = makeRepo();
    await runEnvSetup(makeHeadlessStore(), repo, "selfhost", { 3000: 4000 });

    const composeEnv = readFileSync(
      path.join(repo, "infra", "docker", ".env"),
      "utf-8",
    );
    expect(composeEnv).toMatch(/^WEB_HOST_PORT=4000$/m);
    expect(composeEnv).toMatch(/^COMPOSE_PROFILES=proxy$/m);
    expect(composeEnv).toMatch(/^DOCKER_SOCKET_GID=\d+$/m);
    expect(composeEnv).not.toMatch(/NEXT_PUBLIC_APP_URL/);

    const apiEnv = readApiEnv(repo);
    expect(apiEnv).toMatch(/^HOST=http:\/\/localhost:4000$/m);
    expect(apiEnv).toMatch(/^FRONTEND_URL=http:\/\/localhost:4000$/m);
  });

  it("points HOST and FRONTEND_URL at https://<domain> and records it", async () => {
    const repo = makeRepo();
    await runEnvSetup(
      makeHeadlessStore(),
      repo,
      "selfhost",
      { 3000: 80, 3443: 443 },
      { domain: "gaia.example.com" },
    );

    const composeEnv = readFileSync(
      path.join(repo, "infra", "docker", ".env"),
      "utf-8",
    );
    expect(composeEnv).toMatch(/^GAIA_DOMAIN=gaia\.example\.com$/m);
    expect(composeEnv).toMatch(/^WEB_HOST_PORT=80$/m);
    expect(composeEnv).toMatch(/^HTTPS_HOST_PORT=443$/m);
    const apiEnv = readApiEnv(repo);
    expect(apiEnv).toMatch(/^HOST=https:\/\/gaia\.example\.com$/m);
    expect(apiEnv).toMatch(/^FRONTEND_URL=https:\/\/gaia\.example\.com$/m);
  });

  it("--no-domain drops the domain and puts GAIA back on its default ports", async () => {
    const repo = makeRepo();
    await runEnvSetup(
      makeHeadlessStore(),
      repo,
      "selfhost",
      { 3000: 80, 3443: 443 },
      { domain: "gaia.test" },
    );

    await runEnvSetup(
      makeHeadlessStore(),
      repo,
      "selfhost",
      { 3000: 3000, 3443: 3443 },
      { domain: false },
    );

    const composeEnv = readFileSync(
      path.join(repo, "infra", "docker", ".env"),
      "utf-8",
    );
    expect(composeEnv).toMatch(/^WEB_HOST_PORT=3000$/m);
    expect(composeEnv).toMatch(/^HTTPS_HOST_PORT=3443$/m);
    expect(composeEnv).not.toMatch(/GAIA_DOMAIN/);
    expect(composeEnv).not.toMatch(/GAIA_CADDY_GLOBAL_OPTIONS/);
    const apiEnv = readApiEnv(repo);
    expect(apiEnv).toMatch(/^HOST=http:\/\/localhost:3000$/m);
    expect(apiEnv).toMatch(/^FRONTEND_URL=http:\/\/localhost:3000$/m);
  });
});
