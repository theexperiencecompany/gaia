"""Write .env.worktree: this worktree's own ports, Mongo database, Redis and RabbitMQ vhost.

The main checkout keeps the defaults (8000/3000, the shared GAIA database). A linked
worktree gets a slot no other worktree holds, and every port, name and URL derives from it.
--default-ports gives a linked worktree the main checkout's slot instead, for OAuth work,
whose providers only know localhost:8000 and :3000.
"""

from __future__ import annotations

import argparse
from collections.abc import Iterable
from dataclasses import dataclass
import fcntl
from pathlib import Path
import re
import subprocess
import sys
import zlib

ENV_FILE = ".env.worktree"
SLOT_COUNT = 199
PORT_STEP = 10
# Ports a linked worktree must never take: the main checkout's own, the shared docker
# infra's, and the macOS AirPlay receiver's.
MAIN_CHECKOUT_PORTS = (3000, 3200, 3201, 3202, 3203, 3204, 8000, 9100, 9797)
SHARED_INFRA_PORTS = (5432, 5672, 6379, 8080, 8765, 8888, 15672, 15692, 27017)
AIRPLAY_PORTS = (5000, 7000)
RESERVED_PORTS = frozenset((*MAIN_CHECKOUT_PORTS, *SHARED_INFRA_PORTS, *AIRPLAY_PORTS))
_SLOT_LINE = re.compile(r"^GAIA_WT_SLOT=(\d+)$", re.MULTILINE)
_LEGACY_API_PORT_LINE = re.compile(r"^API_PORT=(\d+)$", re.MULTILINE)
_BOTS = ("DISCORD", "SLACK", "TELEGRAM", "WHATSAPP", "IMESSAGE")


@dataclass(frozen=True)
class Allocation:
    """Every port and name one worktree slot owns; slot 0 is the main checkout."""

    slot: int

    @property
    def offset(self) -> int:
        """Return how far this slot's ports sit from the main checkout's."""
        return self.slot * PORT_STEP

    def ports(self) -> dict[str, int]:
        """Return each port this slot binds, by its env var name."""
        o = self.offset
        ports = {
            "API_PORT": 8000 + o,
            "WEB_PORT": 3000 + o,
            "LLM_STUB_PORT": 9797 + o,
            "ARQ_METRICS_PORT": 9100 if self.slot == 0 else 8005 + o,
        }
        for index, bot in enumerate(_BOTS):
            ports[f"BOT_{bot}_PORT"] = 3200 + index if self.slot == 0 else 3001 + o + index
        if self.slot:
            ports["WT_REDIS_PORT"] = 6383 + o
        return ports

    def is_clear_of_reserved(self) -> bool:
        """Return whether none of this slot's ports is one the main checkout or the infra holds."""
        return self.slot == 0 or RESERVED_PORTS.isdisjoint(self.ports().values())

    def env_lines(self) -> list[str]:
        """Return the .env.worktree body for this slot."""
        ports = self.ports()
        api, web = ports["API_PORT"], ports["WEB_PORT"]
        lines = [
            "# Auto-generated by `mise run wt:env`: do not edit, do not commit.",
            "# mise loads it for every task. Rerun `mise run wt:env` to regenerate it.",
            f"GAIA_WT_SLOT={self.slot}",
            "ENV=development",
            *(f"{name}={port}" for name, port in ports.items()),
            f"API_HOST_PORT={api}",
            f"FRONTEND_URL=http://localhost:{web}",
            f"NEXT_PUBLIC_API_BASE_URL=http://localhost:{api}/api/v1/",
            f"GAIA_API_URL=http://localhost:{api}",
            f"HOST=http://localhost:{api}",
        ]
        if self.slot:
            # Named by offset, so a worktree keeps the Chroma collections it already indexed.
            name = f"gaia_wt{self.offset}"
            lines += [
                f"MONGO_DB_NAME={name}",
                f"REDIS_URL=redis://localhost:{ports['WT_REDIS_PORT']}/0",
                f"RABBITMQ_VHOST={name}",
                f"RABBITMQ_URL=amqp://guest:guest@localhost:5672/{name}",  # pragma: allowlist secret
                f"GAIA_CHROMA_COLLECTION_SUFFIX=_wt{self.offset}",
            ]
        return lines


def slot_in(env_file: Path) -> int | None:
    """Return the slot an existing .env.worktree holds, reading a pre-slot file by its API port."""
    if not env_file.is_file():
        return None
    text = env_file.read_text()
    if match := _SLOT_LINE.search(text):
        return int(match.group(1))
    if match := _LEGACY_API_PORT_LINE.search(text):
        return (int(match.group(1)) - 8000) // PORT_STEP
    return None


def preferred_slot(root: Path) -> int:
    """Return the slot this path hashes to, so a worktree lands on the same one each time."""
    return zlib.crc32(str(root).encode()) % SLOT_COUNT + 1


def allocate(root: Path, other_roots: Iterable[Path]) -> int:
    """Return a slot for root that no other worktree holds: its current one, else the next free."""
    taken = {slot for other in other_roots if (slot := slot_in(other / ENV_FILE))}
    current = slot_in(root / ENV_FILE)
    if current and current not in taken and Allocation(current).is_clear_of_reserved():
        return current
    start = preferred_slot(root)
    for step in range(SLOT_COUNT):
        slot = (start - 1 + step) % SLOT_COUNT + 1
        if slot not in taken and Allocation(slot).is_clear_of_reserved():
            return slot
    raise SystemExit(
        f"wt:env: all {SLOT_COUNT} worktree slots are taken. "
        "Remove worktrees you no longer use (`git worktree remove <path>`) and rerun."
    )


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout.strip()


def _worktree_roots() -> list[Path]:
    porcelain = _git("worktree", "list", "--porcelain")
    return [
        Path(line.split(" ", 1)[1])
        for line in porcelain.splitlines()
        if line.startswith("worktree ")
    ]


def main(argv: list[str] | None = None) -> None:
    """Allocate this worktree's slot under a repo-wide lock and write its .env.worktree."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--default-ports",
        action="store_true",
        help="use the main checkout's ports and shared services (OAuth callbacks need 8000/3000)",
    )
    default_ports = parser.parse_args(argv).default_ports
    root = Path(_git("rev-parse", "--show-toplevel")).resolve()
    git_dir = Path(_git("rev-parse", "--absolute-git-dir")).resolve()
    common_dir = Path(_git("rev-parse", "--path-format=absolute", "--git-common-dir")).resolve()
    # Two worktrees allocating at once must not both see the same slot free.
    with (common_dir / "gaia-wt-env.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if git_dir == common_dir or default_ports:
            slot = 0
        else:
            others = [p.resolve() for p in _worktree_roots() if p.resolve() != root]
            slot = allocate(root, others)
        allocation = Allocation(slot)
        (root / ENV_FILE).write_text("\n".join(allocation.env_lines()) + "\n")
    ports = allocation.ports()
    print(
        f"wt:env → {root / ENV_FILE} (slot {slot}): "
        f"API_PORT={ports['API_PORT']} WEB_PORT={ports['WEB_PORT']}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
