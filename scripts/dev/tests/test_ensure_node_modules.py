"""A fresh worktree's commit hooks install node_modules once instead of dying on ERR_MODULE_NOT_FOUND."""

from __future__ import annotations

import os
from pathlib import Path
import re
import subprocess

import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
SCRIPT = REPO_ROOT / "scripts" / "dev" / "ensure-node-modules.sh"
HOOK_ID = "ensure-node-modules"
# The hook configs prek runs in workspace mode: the root and the nested projects that run node.
HOOK_CONFIGS = [
    REPO_ROOT / ".pre-commit-config.yaml",
    REPO_ROOT / "apps/web/.pre-commit-config.yaml",
]
NODE_ENTRY_RE = re.compile(r"\b(pnpm|node)\b")


@pytest.fixture
def checkout(tmp_path: Path) -> Path:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    return tmp_path


def run_hook(checkout: Path, tmp_path_factory: pytest.TempPathFactory) -> list[str]:
    """Run the hook in checkout with a pnpm that records its argv; return the recorded calls."""
    bin_dir = tmp_path_factory.mktemp("bin")
    log = bin_dir / "pnpm.log"
    pnpm = bin_dir / "pnpm"
    pnpm.write_text(f'#!/bin/sh\necho "$@" >> {log}\n')
    pnpm.chmod(0o755)
    env = {**os.environ, "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}"}
    subprocess.run(["bash", str(SCRIPT)], cwd=checkout, env=env, check=True)
    return log.read_text().splitlines() if log.exists() else []


def test_a_checkout_with_no_node_modules_installs_them_once(
    checkout: Path, tmp_path_factory: pytest.TempPathFactory
) -> None:
    calls = run_hook(checkout, tmp_path_factory)
    assert calls == [f"--dir {checkout.resolve()} install --frozen-lockfile --prefer-offline"]


def test_an_install_cancelled_before_it_finished_is_run_again(
    checkout: Path, tmp_path_factory: pytest.TempPathFactory
) -> None:
    (checkout / "node_modules").mkdir()
    (checkout / "node_modules" / ".modules.yaml").write_text("")
    assert len(run_hook(checkout, tmp_path_factory)) == 1


def test_a_finished_install_is_left_alone(
    checkout: Path, tmp_path_factory: pytest.TempPathFactory
) -> None:
    (checkout / "node_modules" / ".pnpm").mkdir(parents=True)
    (checkout / "node_modules" / ".modules.yaml").write_text("")
    (checkout / "node_modules" / ".pnpm" / "lock.yaml").write_text("")
    assert run_hook(checkout, tmp_path_factory) == []


@pytest.mark.parametrize("config", HOOK_CONFIGS, ids=lambda p: str(p.relative_to(REPO_ROOT)))
def test_the_install_runs_before_every_hook_that_runs_node(config: Path) -> None:
    hooks = [hook for repo in yaml.safe_load(config.read_text())["repos"] for hook in repo["hooks"]]
    ensure = next(hook for hook in hooks if hook["id"] == HOOK_ID)
    # prek runs a lower priority first; an unset one is the hook's position, after the explicit 0.
    node_hooks = [h for h in hooks if NODE_ENTRY_RE.search(h.get("entry", "")) and h is not ensure]
    assert node_hooks, f"{config} runs no node hook, so it needs no {HOOK_ID}"
    assert ensure["priority"] == 0
    assert all(h.get("priority", hooks.index(h)) > 0 for h in node_hooks)
