GENERATED_NOTICE = (
    "# Generated by scripts/ci/lib/deploy_templates.py from infra/docker/docker-compose.selfhost.yml,\n"
    "# its Caddyfile and the CLI's machine secrets: edit those, then run `mise deploy:templates`."
)

YamlMap = dict[str, Any]


class Note:
    """A value with the comment written above its key or list item."""

    def __init__(self, comment: str, value: object) -> None:
        self.comment = comment
        self.value = value


class Flow(list[Any]):
    """A list written on one line: an exec-form command or a healthcheck test."""


class Block(str):
    """A string written as a literal block: an inline file."""

    __slots__ = ()


class Spaced(dict[str, Any]):
    """A mapping whose entries are separated by a blank line: the services."""


class SpacedList(list[Any]):
    """A list whose items are separated by a blank line: the services."""


class Anchored(dict[str, Any]):
    """A mapping written once under a YAML anchor, for Merged mappings to share."""

    def __init__(self, anchor: str, mapping: YamlMap) -> None:
        super().__init__(mapping)
        self.anchor = anchor


class Merged(dict[str, Any]):
    """A mapping written as `<<: *anchor` plus its own entries."""

    def __init__(self, base: Anchored, own: YamlMap) -> None:
        super().__init__(own)
        self.base = base


# ─── Shared: what the compose file says that no platform template carries ───

#: Compose keys that only mean something to a local `docker compose` run.
LOCAL_ONLY_KEYS = {
    "logging",
    "restart",
    "expose",
    "ports",
    "profiles",
    "networks",
    "env_file",
    "tty",
    "stdin_open",
    "extra_hosts",
    # seccomp-mongo.json is a file beside the compose file; neither platform ships it.
    "security_opt",
}

#: Backend variables that need extra_hosts (host.docker.internal), which no platform template sets.
HOST_GATEWAY_ENV = {"LOOPBACK_HOST_ALIAS"}

_INTERPOLATION_RE = re.compile(r"\$\{(\w+):-([^}]*)\}")


def _machine_secrets() -> list[str]:
    secrets = json.loads(MACHINE_SECRETS.read_text())
    return [*secrets["always"], *secrets["freshInstallOnly"]]


def _resolve_image(image: str, keep: set[str]) -> str:
    """Replace each ${VAR:-default} whose VAR is not in keep with its default."""
    return _INTERPOLATION_RE.sub(lambda m: m.group(0) if m.group(1) in keep else m.group(2), image)


def _env_map(environment: list[str] | YamlMap | None) -> YamlMap:
    """Read a service's environment as a mapping, whichever form compose wrote it in."""
    if environment is None:
        return {}
    if isinstance(environment, dict):
        return dict(environment)
    return dict(entry.split("=", 1) for entry in environment)


def _require_all(platform: str, what: str, wanted: Iterable[str], mapped: Iterable[str]) -> None:
    """Fail loud on anything the platform's table does not map: the template would ship without it."""
    missing = sorted(set(wanted) - set(mapped))
    if missing:
        raise SystemExit(
            f"deploy_templates: {platform} maps no {what} {', '.join(missing)}; add it to its table."
        )


