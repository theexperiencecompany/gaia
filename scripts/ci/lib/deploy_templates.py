def _from_service(kind: str, name: str, **ref: str) -> YamlMap:
    return {"fromService": {"type": kind, "name": name, **ref}}


def _docker_hub(image: str) -> str:
    """Spell an image with its registry, as Render needs: mongo:8 is docker.io/library/mongo:8."""
    name = image.split(":", 1)[0]
    if "/" not in name:
        return f"docker.io/library/{image}"
    return image if "." in name.split("/", 1)[0] else f"docker.io/{image}"


def _render_image(service: YamlMap) -> YamlMap:
    return {"url": _docker_hub(_resolve_image(service["image"], keep=set()))}


def _render_app_group(services: YamlMap, secrets: list[str]) -> list[Any]:
    backend_env = _env_map(services["gaia-backend"]["environment"])
    chroma_env = _env_map(services["chromadb"]["environment"])
    group: list[Any] = [
        {"key": "ENV", "value": "selfhost"},
        {"key": "AUTH_MODE", "value": "local"},
        {"key": "PYTHONUNBUFFERED", "value": str(backend_env["PYTHONUNBUFFERED"])},
        {"key": "PYTHONPATH", "value": backend_env["PYTHONPATH"]},
        {"key": "CHROMADB_PORT", "value": str(chroma_env["CHROMA_SERVER_PORT"])},
        Note(
            "A Render disk attaches to one service, so the backend and the worker\n"
            "cannot share a files volume: files go to Cloudinary instead.",
            {"key": "BLOB_STORE", "value": "cloudinary"},
        ),
        {"key": "CLOUDINARY_CLOUD_NAME", "sync": False},
        {"key": "CLOUDINARY_API_KEY", "sync": False},
        {"key": "CLOUDINARY_API_SECRET", "sync": False},
    ]
    first, *rest = ({"key": name, "generateValue": True} for name in secrets)
    group.append(
        Note("Machine secrets. Generated once; never rotate them after first boot.", first)
    )
    group.extend(rest)
    return group


def _render_app_env(services: YamlMap, name: str) -> list[Any]:
    """List the group, the service's own WORKER_TYPE, then each connection; the worker copies the backend's."""
    env = _env_map(services[name]["environment"])
    own = [
        {"key": key, "value": env[key]}
        for key in ("WORKER_TYPE", "GAIA_SERVICE_NAME")
        if key in env
    ]
    wiring: list[Any] = [
        {
            "key": "POSTGRES_URL",
            "fromDatabase": {"name": "gaia-postgres", "property": "connectionString"},
        },
        {
            "key": "REDIS_URL",
            **_from_service("keyvalue", "gaia-redis", property="connectionString"),
        },
        {"key": "CHROMADB_HOST", **_from_service("pserv", "gaia-chromadb", property="host")},
    ]
    for key, comment in RENDER_AFTER_FIRST_DEPLOY.items():
        if name == "gaia-backend":
            wiring.append(Note(comment, {"key": key, "sync": False}))
        else:
            wiring.append({"key": key, **_from_service("pserv", "gaia-backend", envVarKey=key)})
    return [{"fromGroup": "gaia-app"}, *own, *wiring]


def _render_datastore(services: YamlMap, name: str) -> YamlMap:
    service = services[name]
    source, target = service["volumes"][0].split(":", 1)
    disk_name, size = RENDER_DISKS[source]
    env = [{"key": k, "value": str(v)} for k, v in _env_map(service.get("environment")).items()]
    return {
        "type": "pserv",
        "name": f"gaia-{name}",
        "runtime": "image",
        "image": _render_image(service),
        "plan": RENDER_PLANS[name],
        "envVars": env + RENDER_SERVICE_ENV.get(name, []),
        "disk": {"name": disk_name, "mountPath": target, "sizeGB": size},
    }


