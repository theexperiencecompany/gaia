# ─── YAML output: the hand-written templates' style, comments included ───

_INDICATORS = "-?:,[]{}#&*!|>'\"%@`"


def _scalar(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    text = str(value)
    plain = (
        text
        and text == text.strip()
        and text[0] not in _INDICATORS
        and ": " not in text
        and " #" not in text
        and not text.endswith(":")
        and yaml.safe_load(text) == text
    )
    return text if plain else json.dumps(text, ensure_ascii=False)


def _comment(note: object, indent: int, lines: list[str]) -> object:
    """Write a Note's comment lines and return its value; return anything else as is."""
    if not isinstance(note, Note):
        return note
    lines.extend(f"{' ' * indent}# {line}" for line in note.comment.split("\n"))
    return note.value


def _emit_value(prefix: str, value: object, indent: int, lines: list[str]) -> None:
    if isinstance(value, Anchored):
        lines.append(f"{prefix} &{value.anchor}")
        _emit_mapping(value, indent + 2, lines)
    elif isinstance(value, Merged):
        lines.extend([prefix, f"{' ' * (indent + 2)}<<: *{value.base.anchor}"])
        _emit_mapping(value, indent + 2, lines)
    elif isinstance(value, Block):
        lines.append(f"{prefix} |")
        lines.extend(
            f"{' ' * (indent + 2)}{line}" if line else "" for line in value.rstrip("\n").split("\n")
        )
    elif isinstance(value, Flow):
        lines.append(f"{prefix} [{', '.join(json.dumps(item) for item in value)}]")
    elif isinstance(value, dict) and value:
        lines.append(prefix)
        _emit_mapping(value, indent + 2, lines)
    elif isinstance(value, list) and value:
        lines.append(prefix)
        _emit_list(value, indent + 2, lines)
    elif isinstance(value, (dict, list)):
        lines.append(f"{prefix} {'{}' if isinstance(value, dict) else '[]'}")
    else:
        text = _scalar(value)
        lines.append(f"{prefix} {text}" if text else prefix)


def _emit_mapping(mapping: YamlMap, indent: int, lines: list[str]) -> None:
    for index, (key, raw) in enumerate(mapping.items()):
        if isinstance(mapping, Spaced) and index:
            lines.append("")
        value = _comment(raw, indent, lines)
        _emit_value(f"{' ' * indent}{key}:", value, indent, lines)


def _emit_list(items: list[Any], indent: int, lines: list[str]) -> None:
    for index, raw in enumerate(items):
        if isinstance(items, SpacedList) and index:
            lines.append("")
        item = _comment(raw, indent, lines)
        if isinstance(item, dict) and item:
            nested: list[str] = []
            _emit_mapping(item, indent + 2, nested)
            lines.append(f"{' ' * indent}- {nested[0][indent + 2 :]}")
            lines.extend(nested[1:])
        else:
            lines.append(f"{' ' * indent}- {_scalar(item)}")


def _plain(value: object) -> object:
    """Return the document as yaml.safe_load reads it back: Notes unwrapped, markers dropped."""
    if isinstance(value, Note):
        return _plain(value.value)
    if isinstance(value, Merged):
        return {**_plain_mapping(value.base), **_plain_mapping(value)}
    if isinstance(value, dict):
        return _plain_mapping(value)
    if isinstance(value, list):
        return [_plain(item) for item in value]
    return str(value) if isinstance(value, Block) else value


def _plain_mapping(mapping: YamlMap) -> YamlMap:
    return {key: _plain(item) for key, item in mapping.items()}


def render_yaml(header: str, document: YamlMap) -> str:
    """Write the document under its header, and prove it reads back as the same data."""
    lines: list[str] = []
    _emit_mapping(document, 0, lines)
    body = "\n".join(lines) + "\n"
    if yaml.safe_load(body) != _plain(document):
        raise SystemExit(
            "deploy_templates: the emitted YAML does not read back as the data it was given"
        )
    return f"{header}\n{GENERATED_NOTICE}\n\n{body}"


def main() -> int:
    """Write every deploy template from the compose file, the Caddyfile and the secret list."""
    compose = yaml.safe_load(COMPOSE.read_text())
    secrets = _machine_secrets()
    COOLIFY_OUT.write_text(render_yaml(*build_coolify(compose, secrets)))
    RENDER_OUT.write_text(render_yaml(*build_render(compose, secrets)))
    PROXY_DOCKERFILE_OUT.write_text(build_proxy_dockerfile(compose))
    return 0


if __name__ == "__main__":
    sys.exit(main())
