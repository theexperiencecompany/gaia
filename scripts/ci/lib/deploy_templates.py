def _coolify_env(name: str, service: YamlMap, shared_env: Anchored) -> Merged | list[str]:
    """App services merge the shared backend env, then add their own; the rest list theirs."""
    env = _env_map(service.get("environment"))
    if name in COOLIFY_APP_SERVICES:
        own = {
            k: v
            for k, v in env.items()
            if k not in HOST_GATEWAY_ENV and shared_env.get(k, object()) != v
        }
        return Merged(shared_env, own)
    env = {**env, **COOLIFY_SERVICE_ENV.get(name, {})}
    return [key if value is None else f"{key}={value}" for key, value in env.items()]


def _coolify_volumes(service: YamlMap) -> list[str]:
    mounts = [mount.split(":", 1) for mount in service.get("volumes", [])]
    _require_all("Coolify", "volume", (source for source, _ in mounts), COOLIFY_VOLUMES)
    return [f"{COOLIFY_VOLUMES[source]}:{target}" for source, target in mounts]


def _coolify_service(name: str, service: YamlMap, shared_env: Anchored) -> YamlMap:
    out: YamlMap = {"image": _resolve_image(service["image"], keep={"GAIA_VERSION"})}
    if "command" in service:
        out["command"] = Flow(service["command"])
    env = _coolify_env(name, service, shared_env)
    if env:
        out["environment"] = env
    if "volumes" in service:
        out["volumes"] = _coolify_volumes(service)
    if "depends_on" in service:
        out["depends_on"] = {
            COOLIFY_SERVICES[dep]: cond for dep, cond in service["depends_on"].items()
        }
    out["healthcheck"] = {**service["healthcheck"], "test": Flow(service["healthcheck"]["test"])}
    unhandled = set(service) - LOCAL_ONLY_KEYS - set(out) - {"environment"}
    if unhandled:
        raise SystemExit(
            f"deploy_templates: Coolify does not map {name}'s {', '.join(sorted(unhandled))}"
        )
    return out


_CADDY_PLACEHOLDER_RE = re.compile(r"\{\$(\w+)(?::([^}]*))?\}")


def _coolify_caddyfile() -> Block:
    """Resolve the Caddyfile's {$VAR} and {$VAR:default} placeholders to Coolify's values."""

    def value(match: re.Match[str]) -> str:
        name, default = match.group(1), match.group(2)
        if name in COOLIFY_CADDY_VALUES:
            return COOLIFY_CADDY_VALUES[name]
        if default is None:
            raise SystemExit(
                f"deploy_templates: Coolify has no value for the Caddyfile's {{${name}}}"
            )
        return default

    text = _CADDY_PLACEHOLDER_RE.sub(value, CADDYFILE.read_text())
    # Tabs become spaces: a YAML block scalar cannot carry a tab indent.
    return Block("\n".join(line.rstrip() for line in text.replace("\t", "    ").split("\n")))


def _coolify_proxy(compose_proxy: YamlMap) -> YamlMap:
    # The Caddyfile carries the compose proxy's environment, resolved; Coolify's
    # proxy holds the certificates, so no caddy_data.
    inline = {**compose_proxy, "environment": None, "volumes": []}
    proxy = _coolify_service("proxy", inline, Anchored("unused", {}))
    proxy["volumes"] = [
        {
            "type": "bind",
            "source": "./Caddyfile",
            "target": "/etc/caddy/Caddyfile",
            "read_only": True,
            "content": _coolify_caddyfile(),
        }
    ]
    return proxy


def build_coolify(compose: YamlMap, secrets: list[str]) -> tuple[str, YamlMap]:
    """Build the Coolify one-click template: the compose stack, its magic variables, the Caddyfile inline."""
    services = compose["services"]
    _require_all("Coolify", "service", services, COOLIFY_SERVICES)
    _require_all("Coolify", "machine secret", secrets, COOLIFY_SECRETS)
    backend_env = _env_map(services["gaia-backend"]["environment"])
    shared_env = Anchored(
        "backend_environment",
        {
            **{
                k: v
                for k, v in backend_env.items()
                if k != "WORKER_TYPE" and k not in HOST_GATEWAY_ENV
            },
            **COOLIFY_BACKEND_ENV,
            **{name: COOLIFY_SECRETS[name] for name in secrets},
            **COOLIFY_PROVIDER_ENV,
        },
    )
    out_services = Spaced()
    for name, coolify_name in COOLIFY_SERVICES.items():
        if name == "proxy":
            out_services[coolify_name] = _coolify_proxy(services["proxy"])
        else:
            out_services[coolify_name] = _coolify_service(name, services[name], shared_env)
    used = {
        mount.split(":", 1)[0]
        for service in out_services.values()
        for mount in service.get("volumes", [])
        if isinstance(mount, str)
    }
    document = Spaced(
        {"x-backend-environment": shared_env},
        services=out_services,
        volumes={volume: None for volume in COOLIFY_VOLUMES.values() if volume in used},
    )
    return COOLIFY_HEADER, document


