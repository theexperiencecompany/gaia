#!/usr/bin/env python3
"""Generate the one-click deploy templates from the self-host compose file.

deploy/coolify/gaia.yaml, render.yaml and deploy/proxy.Dockerfile all describe
the stack in infra/docker/docker-compose.selfhost.yml, served through
infra/docker/selfhost/Caddyfile, with the machine secrets the CLI generates
(packages/cli/src/lib/machine-secrets.json). Neither platform can read that
compose file as it stands: Render takes its own Blueprint format, and a Coolify
one-click template needs its magic SERVICE_* variables and an inline Caddyfile.
So this reads the three sources and writes all three files; everything a
platform needs that the compose file does not say lives in the tables below.

Run through `node scripts/ci/checks.mjs deploy-templates [--write]`
(`mise deploy:templates`), which also fails CI when a committed file drifts.

Usage: deploy_templates.py
"""

