import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport:{width:1440,height:900} });
const page = await ctx.newPage();
const reqStart = new Map();
page.on('request', r => { if (r.url().endsWith('.js')) reqStart.set(r.url().split('/').pop(), {t: Date.now()-t0, type: r.resourceType()}); });
const t0 = Date.now();
await page.goto('http://localhost:3200/', {waitUntil:'load'});
await page.waitForTimeout(5000);
const info = await page.evaluate(() => {
  const scripts = [...document.querySelectorAll('script[src]')].map(s=>s.src.split('/').pop());
  const preloads = [...document.querySelectorAll('link[rel="preload"][as="script"], link[rel="modulepreload"]')].map(l=>l.href.split('/').pop());
  const res = performance.getEntriesByType('resource').filter(r=>r.name.endsWith('.js')).map(r=>({n:r.name.split('/').pop(),kb:+(r.encodedBodySize/1024).toFixed(1),start:Math.round(r.startTime),init:r.initiatorType}));
  return {scripts, preloads, res, scriptTags: document.querySelectorAll('script').length};
});
await browser.close();
import fs from 'node:fs';
fs.writeFileSync('/Users/aryan/Downloads/hv3review/split.json', JSON.stringify({...info, reqStart:Object.fromEntries(reqStart)},null,1));
const by = Object.fromEntries(info.res.map(r=>[r.n,r]));
const eager = info.scripts.reduce((a,n)=>a+(by[n]?.kb||0),0);
const pre = info.preloads.filter(n=>!info.scripts.includes(n));
const preKB = pre.reduce((a,n)=>a+(by[n]?.kb||0),0);
console.log('script tags', info.scripts.length, 'eager kB', eager.toFixed(1));
console.log('preload links', info.preloads.length, 'non-script preloads', pre.length, 'preloaded kB', preKB.toFixed(1));
console.log('all js kB', info.res.reduce((a,b)=>a+b.kb,0).toFixed(1));
console.log('--- non-eager (preloaded / lazy) ---');
for (const n of pre) console.log((by[n]?.kb||0)+'kB', n, 'init', by[n]?.init, 'start', by[n]?.start);
