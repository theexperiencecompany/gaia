import { chromium } from "@playwright/test";
const browser = await chromium.launch();
const page = await (await browser.newContext()).newPage();
await page.goto("http://localhost:3200/features", { waitUntil:"domcontentloaded" });
await page.waitForTimeout(3000);
const snap = await page.locator("input").first().ariaSnapshot();
console.log("features-search:", snap);
await page.goto("http://localhost:3200/blog/create", { waitUntil:"domcontentloaded" });
await page.waitForTimeout(3000);
console.log("content-textarea:", await page.locator("textarea").first().ariaSnapshot());
console.log("slug-input:", await page.locator("input[name=slug]").ariaSnapshot());
await browser.close();
